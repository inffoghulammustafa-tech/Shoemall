export const USD_TO_PKR = 280;

export const formatCurrency = (usdPrice: number, currency: 'USD' | 'PKR'): string => {
  if (currency === 'PKR') {
    const pkrVal = Math.round(usdPrice * USD_TO_PKR);
    return `Rs. ${pkrVal.toLocaleString()}`;
  }
  return `$${usdPrice.toFixed(2)}`;
};

